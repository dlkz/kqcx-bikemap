package com.kqcx.bikemap;

import android.content.Context;

import org.json.JSONArray;
import org.json.JSONException;
import org.json.JSONObject;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Index of the vehicle numbers known to the application.
 *
 * <p>It is the union of three sources, in descending priority:
 * <ol>
 *   <li>the exact numbers bundled in {@code assets/vehicle_number_catalog.json};</li>
 *   <li>a series-level {@code seed} fallback, used only when a series maps to a
 *       single campus, so a number the scan has not seen yet still resolves;</li>
 *   <li>hints learned locally while the user looked up a bike by number.</li>
 * </ol>
 *
 * <p>The bundled asset is generated by
 * {@code tools/generate_vehicle_number_catalog.py}; do not hand-edit it.
 */
final class VehicleNumberCatalog {
    static final int NUMBER_LENGTH = 9;
    static final int SERIES_LENGTH = 6;
    static final int TAIL_LENGTH = 3;

    static final class Site {
        final int id;
        final String name;
        final List<String> series;

        Site(int id, String name, List<String> series) {
            this.id = id;
            this.name = name;
            this.series = Collections.unmodifiableList(series);
        }
    }

    static final class NumberInfo {
        final String number;
        final int siteId;
        final String siteName;
        final String series;

        NumberInfo(
                String number,
                int siteId,
                String siteName,
                String series
        ) {
            this.number = number;
            this.siteId = siteId;
            this.siteName = siteName;
            this.series = series;
        }

    }

    private final List<Site> sites;
    private final Map<Integer, Site> sitesById;
    private final Map<String, NumberInfo> byNumber;
    private final Map<String, List<NumberInfo>> bySiteSeries;
    private final Map<String, List<Integer>> seedBySeries;
    private final String updatedAt;

    private VehicleNumberCatalog(
            List<Site> sites,
            Map<String, NumberInfo> byNumber,
            Map<String, List<NumberInfo>> bySiteSeries,
            Map<String, List<Integer>> seedBySeries,
            String updatedAt
    ) {
        this.sites = Collections.unmodifiableList(sites);
        this.byNumber = Collections.unmodifiableMap(byNumber);
        this.bySiteSeries = Collections.unmodifiableMap(bySiteSeries);
        this.seedBySeries = Collections.unmodifiableMap(seedBySeries);
        this.updatedAt = updatedAt == null ? "" : updatedAt;
        Map<Integer, Site> indexedSites = new HashMap<>();
        for (Site site : sites) {
            indexedSites.put(site.id, site);
        }
        this.sitesById = Collections.unmodifiableMap(indexedSites);
    }

    /**
     * Degraded index with no sites and no numbers, used when the bundled asset
     * cannot be read or parsed.  The map and the nearby-vehicle queries keep
     * working; only the number lookup is unavailable.  This exists so a broken
     * or future-format catalog degrades the feature instead of aborting startup.
     */
    static VehicleNumberCatalog empty() {
        return new VehicleNumberCatalog(
                new ArrayList<>(),
                new HashMap<>(),
                new LinkedHashMap<>(),
                new HashMap<>(),
                ""
        );
    }

    static VehicleNumberCatalog load(Context context) throws IOException, JSONException {
        String json;
        try (InputStream input = context.getAssets().open("vehicle_number_catalog.json");
             BufferedReader reader = new BufferedReader(new InputStreamReader(
                     input,
                     StandardCharsets.UTF_8
             ))) {
            StringBuilder builder = new StringBuilder();
            String line;
            while ((line = reader.readLine()) != null) {
                builder.append(line);
            }
            json = builder.toString();
        }

        JSONObject root = new JSONObject(json);
        JSONArray siteArray = root.getJSONArray("sites");
        List<Site> sites = new ArrayList<>();
        Map<Integer, String> siteNames = new HashMap<>();
        for (int index = 0; index < siteArray.length(); index++) {
            JSONObject item = siteArray.getJSONObject(index);
            int id = item.getInt("id");
            String name = item.getString("name");
            JSONArray seriesArray = item.getJSONArray("series");
            List<String> series = new ArrayList<>();
            for (int seriesIndex = 0; seriesIndex < seriesArray.length(); seriesIndex++) {
                series.add(seriesArray.getString(seriesIndex));
            }
            sites.add(new Site(id, name, series));
            siteNames.put(id, name);
        }

        Map<String, NumberInfo> byNumber = new HashMap<>();
        Map<String, List<NumberInfo>> bySiteSeries = new LinkedHashMap<>();
        JSONObject numberObject = root.getJSONObject("numbers");
        java.util.Iterator<String> keys = numberObject.keys();
        while (keys.hasNext()) {
            String number = keys.next();
            JSONArray details = numberObject.getJSONArray(number);
            int siteId = details.getInt(0);
            String series = details.getString(1);
            NumberInfo info = new NumberInfo(
                    number,
                    siteId,
                    siteNames.get(siteId),
                    series
            );
            byNumber.put(number, info);
            bySiteSeries.computeIfAbsent(key(siteId, series), ignored -> new ArrayList<>())
                    .add(info);
        }

        Map<String, List<Integer>> seedBySeries = new HashMap<>();
        JSONObject seedObject = root.optJSONObject("seed");
        if (seedObject != null) {
            java.util.Iterator<String> seedKeys = seedObject.keys();
            while (seedKeys.hasNext()) {
                String series = seedKeys.next();
                JSONArray ids = seedObject.optJSONArray(series);
                if (ids == null) {
                    continue;
                }
                List<Integer> resolved = new ArrayList<>();
                for (int index = 0; index < ids.length(); index++) {
                    resolved.add(ids.optInt(index, -1));
                }
                seedBySeries.put(series, resolved);
            }
        }

        mergeLearned(context, sites, byNumber, bySiteSeries);

        for (List<NumberInfo> values : bySiteSeries.values()) {
            values.sort((left, right) -> left.number.compareTo(right.number));
        }
        sites.sort((left, right) -> Integer.compare(left.id, right.id));
        return new VehicleNumberCatalog(
                sites,
                byNumber,
                bySiteSeries,
                seedBySeries,
                root.optString("updatedAt", "")
        );
    }

    /**
     * Folds locally learned hints into the index.  Bundled numbers always win,
     * so a learned entry can never overwrite the catalog that shipped with the
     * app.  A learned campus that does not match any bundled site keeps
     * {@code siteId == -1}: it still answers exact lookups, but it is not
     * offered in the campus picker.
     *
     * <p>Learned entries that the bundled catalog already covers are dropped
     * from the local store.  Keeping them would be pointless (the bundled entry
     * wins anyway) and harmful later on: if a future release removes that
     * number because the bike was retired, the stale learned entry would bring
     * the number back.  Pruning here keeps "bundled wins, learned only fills
     * gaps" true across upgrades.
     */
    private static void mergeLearned(
            Context context,
            List<Site> sites,
            Map<String, NumberInfo> byNumber,
            Map<String, List<NumberInfo>> bySiteSeries
    ) {
        Map<String, Integer> siteIdByName = new HashMap<>();
        for (Site site : sites) {
            siteIdByName.put(site.name, site.id);
        }
        LearnedVehicleNumberStore store = LearnedVehicleNumberStore.get(context);
        List<String> alreadyBundled = new ArrayList<>();
        for (LearnedVehicleNumberStore.Entry entry : store.entries()) {
            if (byNumber.containsKey(entry.number)) {
                alreadyBundled.add(entry.number);
                continue;
            }
            String siteName = BikeRepository.correctSiteName(entry.siteName);
            Integer matched = siteIdByName.get(siteName);
            int siteId = matched == null ? -1 : matched;
            NumberInfo info = new NumberInfo(
                    entry.number,
                    siteId,
                    siteName,
                    entry.series
            );
            byNumber.put(entry.number, info);
            bySiteSeries.computeIfAbsent(key(siteId, entry.series), ignored -> new ArrayList<>())
                    .add(info);
        }
        if (!alreadyBundled.isEmpty()) {
            store.removeAll(alreadyBundled);
        }
    }

    static String normalize(String value) {
        if (value == null) {
            return "";
        }
        StringBuilder digits = new StringBuilder();
        for (int index = 0; index < value.length(); index++) {
            char character = value.charAt(index);
            if (Character.isDigit(character)) {
                digits.append(character);
            }
        }
        while (digits.length() < NUMBER_LENGTH) {
            digits.insert(0, '0');
        }
        return digits.toString();
    }

    List<Site> sites() {
        return sites;
    }

    /** ISO date (yyyy-MM-dd) the bundled catalog was generated, or "" if absent. */
    String updatedAt() {
        return updatedAt;
    }

    Site site(int siteId) {
        return sitesById.get(siteId);
    }

    NumberInfo find(String number) {
        String normalized = normalize(number);
        NumberInfo info = byNumber.get(normalized);
        if (info != null) {
            return info;
        }
        return inferFromSeed(normalized);
    }

    /**
     * Last-resort lookup: when a full number is not in the exact index but its
     * 6-digit series is known to belong to exactly one campus, attribute it to
     * that campus.  Series shared by several campuses stay unresolved rather
     * than guessing.
     */
    private NumberInfo inferFromSeed(String normalized) {
        if (normalized.length() != NUMBER_LENGTH) {
            return null;
        }
        List<Integer> siteIds = seedBySeries.get(normalized.substring(0, SERIES_LENGTH));
        if (siteIds == null || siteIds.size() != 1) {
            return null;
        }
        Site site = sitesById.get(siteIds.get(0));
        if (site == null) {
            return null;
        }
        return new NumberInfo(
                normalized,
                site.id,
                site.name,
                normalized.substring(0, SERIES_LENGTH)
        );
    }

    List<NumberInfo> matchesSuffix(int siteId, String series, String suffix) {
        if (suffix == null
                || suffix.length() < TAIL_LENGTH
                || suffix.length() > 4) {
            return Collections.emptyList();
        }
        List<NumberInfo> matches = new ArrayList<>();
        for (Map.Entry<String, List<NumberInfo>> entry : bySiteSeries.entrySet()) {
            if (!entry.getKey().startsWith(siteId + "|")) {
                continue;
            }
            if (series != null && !entry.getKey().equals(key(siteId, series))) {
                continue;
            }
            for (NumberInfo value : entry.getValue()) {
                if (value.number.endsWith(suffix)) {
                    matches.add(value);
                }
            }
        }
        matches.sort((left, right) -> left.number.compareTo(right.number));
        return matches;
    }

    private static String key(int siteId, String series) {
        return siteId + "|" + series;
    }
}
